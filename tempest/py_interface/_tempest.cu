inline double resolve_temporal_node2vec_parameter(
    const std::optional<double>& temporal_param,
    const double default_value,
    const char* temporal_name) {

    const double value = temporal_param.value_or(default_value);

    if (value <= 0.0) {
        throw std::invalid_argument(
            std::string("'") + temporal_name + "' must be > 0.");
    }

    return value;
}

inline const RandomPickerType* get_picker_ptr_from_optional_string(
    const std::optional<std::string>& picker_str,
    std::optional<RandomPickerType>& picker_enum_storage) {

    if (picker_str.has_value()) {
        picker_enum_storage = picker_type_from_string(*picker_str);
        return &(*picker_enum_storage);
    }
    return nullptr;
}

PYBIND11_MODULE(_tempest, m)
{
    py::class_<Tempest>(m, "Tempest")
        .def(py::init([](
                         const bool is_directed,
                         bool use_gpu,

                         const std::optional<int64_t> max_time_capacity,
                         const std::optional<bool> enable_weight_computation,
                         const std::optional<bool> enable_temporal_node2vec,
                         const std::optional<double> timescale_bound,

                         const std::optional<double> temporal_node2vec_p,
                         const std::optional<double> temporal_node2vec_q,

                         const std::optional<int> walk_padding_value,
                         const std::optional<uint64_t> global_seed,
                         const std::optional<bool> shuffle_walk_order,

                         const std::optional<int> cuda_device_id)
             {
                 return std::make_unique<Tempest>(
                     is_directed,
                     use_gpu,

                     max_time_capacity.value_or(-1),
                     enable_weight_computation.value_or(false),
                     enable_temporal_node2vec.value_or(false),
                     timescale_bound.value_or(DEFAULT_TIMESCALE_BOUND),

                     temporal_node2vec_p.value_or(DEFAULT_NODE2VEC_P),
                     temporal_node2vec_q.value_or(DEFAULT_NODE2VEC_Q),

                     walk_padding_value.value_or(EMPTY_NODE_VALUE),
                     global_seed.value_or(EMPTY_GLOBAL_SEED),
                     shuffle_walk_order.value_or(DEFAULT_SHUFFLE_WALK_ORDER),

                     cuda_device_id.value_or(0));
             }),
             R"(
             Initialize a temporal random walk generator.

             Args:
             is_directed (bool): Whether to create a directed graph.
             use_gpu (bool): Whether to use GPU or not.

             max_time_capacity (int, optional): Maximum time window for edges. Edges older than (latest_time - max_time_capacity) are removed. Use -1 for no limit. Defaults to -1.
             enable_weight_computation (bool, optional): Enable CTDNE weight computation. Required for ExponentialWeight picker. Defaults to False.
             enable_temporal_node2vec (bool, optional): Enable TemporalNode2Vec configuration; when True, weight computation is also enabled. Defaults to False.
             timescale_bound (float, optional): Scale factor for temporal differences. Used to prevent numerical issues with large time differences. Defaults to -1.0.

             temporal_node2vec_p (float, optional): Temporal-node2vec return parameter p (> 0). Defaults to 1.0.
             temporal_node2vec_q (float, optional): Temporal-node2vec in-out parameter q (> 0). Defaults to 1.0.

             walk_padding_value (int, optional): Padding node value for prematurely broken walks. Default is -1.
             global_seed (int, optional): A global seed to have reproducibility inside random walks. Default is empty and the code in that case generates random seed in each run.
             shuffle_walk_order (bool, optional): Should we shuffle walk order in n walks per node (generated by get_random_walks_and_times_for_all_nodes)? Defaults to True.

             cuda_device_id (int, optional): CUDA device index to pin this instance to when use_gpu=True. Lets a multi-GPU process run Tempest on one GPU while another library (e.g. PyTorch) holds a different GPU on the same thread; the device is set on entry to every method and restored on exit. Ignored when use_gpu=False. Defaults to 0.
             )",
             py::arg("is_directed"),
             py::arg("use_gpu") = false,

             py::arg("max_time_capacity") = py::none(),
             py::arg("enable_weight_computation") = py::none(),
             py::arg("enable_temporal_node2vec") = py::none(),
             py::arg("timescale_bound") = py::none(),

             py::arg("temporal_node2vec_p") = py::none(),
             py::arg("temporal_node2vec_q") = py::none(),

             py::arg("walk_padding_value") = py::none(),
             py::arg("global_seed") = py::none(),
             py::arg("shuffle_walk_order") = py::none(),

             py::arg("cuda_device_id") = py::none())

        .def("add_multiple_edges", [](Tempest& tw,
                             const py::array_t<int>& sources,
                             const py::array_t<int>& targets,
                             const py::array_t<int64_t>& timestamps,
                             const py::object& edge_features_obj)
        {
            const auto sources_info = sources.request();
            const auto targets_info = targets.request();
            const auto timestamps_info = timestamps.request();

            if (sources_info.ndim != 1 || targets_info.ndim != 1 || timestamps_info.ndim != 1)
                throw std::runtime_error("Arrays must be 1-dimensional");

            const size_t num_edges = sources_info.shape[0];
            if (targets_info.shape[0] != num_edges || timestamps_info.shape[0] != num_edges)
                throw std::runtime_error("All arrays must have the same length");

            const auto sources_ptr = static_cast<int*>(sources_info.ptr);
            const auto targets_ptr = static_cast<int*>(targets_info.ptr);
            const auto* timestamps_ptr = static_cast<int64_t*>(timestamps_info.ptr);

            const float* edge_features_ptr = nullptr;
            size_t feature_dim = 0;
            std::optional<py::array_t<float, py::array::c_style | py::array::forcecast>> edge_features = std::nullopt;

            if (!edge_features_obj.is_none()) {
                edge_features = edge_features_obj.cast<py::array_t<float, py::array::c_style | py::array::forcecast>>();
                const auto edge_features_info = edge_features->request();

                if (edge_features_info.ndim != 1 && edge_features_info.ndim != 2) {
                    throw std::runtime_error("edge_features must be a 1D or 2D NumPy array");
                }

                const auto num_edge_feature_values = static_cast<size_t>(edge_features_info.size);
                if (num_edges == 0 && num_edge_feature_values > 0) {
                    throw std::runtime_error("edge_features must be empty when there are no edges");
                }

                if (num_edges > 0 && num_edge_feature_values % num_edges != 0) {
                    throw std::runtime_error("edge_features size must be num_edges * feature_dim");
                }

                feature_dim = (num_edges == 0) ? 0 : num_edge_feature_values / num_edges;
                edge_features_ptr = static_cast<float*>(edge_features_info.ptr);
            }

            tw.add_multiple_edges(
                sources_ptr,
                targets_ptr,
                timestamps_ptr,
                num_edges,
                edge_features_ptr,
                feature_dim);
        },
        R"(
        Add multiple edges to the temporal graph.

        Args:
            sources: List or NumPy array of source node IDs (or first node in undirected graphs).
            targets: List or NumPy array of target node IDs (or second node in undirected graph).
            timestamps: List or NumPy array of timestamps representing when interactions occurred.
            edge_features: Optional NumPy array of edge features/weights. The flattened size
                must equal num_edges * feature_dim. Can be either 1D (already flattened)
                or 2D with shape [num_edges, feature_dim].

        Raises:
            RuntimeError: If arrays have invalid dimensions, different edge lengths,
                or edge_features has an invalid total size.

        Note:
            For large datasets, NumPy arrays will provide better performance than Python lists.
        )",
        py::arg("sources"),
        py::arg("targets"),
        py::arg("timestamps"),
        py::arg("edge_features") = py::none()
        )

        .def("set_node_features", [](Tempest& tw,
                              const py::array_t<int>& node_ids,
                              const py::array_t<float, py::array::c_style | py::array::forcecast>& node_features)
        {
            const auto node_ids_info = node_ids.request();
            const auto node_features_info = node_features.request();

            if (node_ids_info.ndim != 1) {
                throw std::runtime_error("node_ids must be a 1D NumPy array");
            }

            if (node_features_info.ndim != 2) {
                throw std::runtime_error("node_features must be a 2D NumPy array");
            }

            const auto num_nodes = static_cast<size_t>(node_ids_info.shape[0]);
            const auto feature_dim = static_cast<size_t>(node_features_info.shape[1]);

            if (static_cast<size_t>(node_features_info.shape[0]) != num_nodes) {
                throw std::runtime_error("node_features row count must match node_ids length");
            }

            if (feature_dim == 0 && num_nodes > 0) {
                throw std::runtime_error("node_features must have at least one column when node_ids is non-empty");
            }

            if (num_nodes == 0) {
                return;
            }

            tw.set_node_features(
                static_cast<const int*>(node_ids_info.ptr),
                num_nodes,
                static_cast<const float*>(node_features_info.ptr),
                feature_dim);
        },
        R"(
        Set dense feature vectors for specific node IDs.

        Args:
            node_ids: 1D NumPy array of node IDs.
            node_features: 2D NumPy array with shape [num_nodes, feature_dim].

        Raises:
            RuntimeError: If node_ids is not 1D, node_features is not 2D,
                or row count does not match number of node IDs.
        )",
        py::arg("node_ids"),
        py::arg("node_features")
        )

        .def("get_node_features", [](const Tempest& tw)
        {
            const int feature_dim_int = tw.node_feature_dim();
            const int max_node_id_int = tw.node_features_max_node_id();
            const std::vector<float> dense = tw.node_features_dense();

            if (feature_dim_int == 0 || max_node_id_int < 0 || dense.empty()) {
                return py::array_t<float>(
                    py::array::ShapeContainer{0, 0},
                    py::array::StridesContainer{0, 0});
            }

            const auto num_rows    = static_cast<ssize_t>(max_node_id_int + 1);
            const auto feature_dim = static_cast<ssize_t>(feature_dim_int);

            py::array_t<float> dense_node_features(
                py::array::ShapeContainer{num_rows, feature_dim},
                py::array::StridesContainer{
                    static_cast<ssize_t>(sizeof(float) * feature_dim),
                    static_cast<ssize_t>(sizeof(float))});

            const size_t total_values = static_cast<size_t>(num_rows) * static_cast<size_t>(feature_dim);
            std::copy_n(
                dense.data(),
                total_values,
                static_cast<float*>(dense_node_features.request().ptr));

            return dense_node_features;
        },
        R"(
        Return dense node features for all node IDs from 0 to max_node_id.

        Returns:
            np.ndarray: 2D float array with shape [max_node_id + 1, feature_dim],
                where row index corresponds to node ID.
        )")

        .def("get_random_walks_and_times_for_all_nodes", [](Tempest& tw,
                                               const int max_walk_len,
                                               const std::string& walk_bias,
                                               const int num_walks_per_node,
                                               const std::optional<std::string>& initial_edge_bias = std::nullopt,
                                               const std::string& walk_direction = "Forward_In_Time",
                                               const std::string& kernel_launch_type = "NODE_GROUPED")
            {
                const RandomPickerType walk_bias_enum = picker_type_from_string(walk_bias);
                std::optional<RandomPickerType> edge_bias_enum_opt;
                const RandomPickerType* initial_edge_bias_enum_ptr = get_picker_ptr_from_optional_string(
                    initial_edge_bias, edge_bias_enum_opt);
                const WalkDirection walk_direction_enum = walk_direction_from_string(walk_direction);
                const KernelLaunchType kernel_launch_type_enum =
                    kernel_launch_type_from_string(kernel_launch_type);

                auto walks = tw.get_random_walks_and_times_for_all_nodes(
                    max_walk_len,
                    &walk_bias_enum,
                    num_walks_per_node,
                    initial_edge_bias_enum_ptr,
                    walk_direction_enum,
                    kernel_launch_type_enum);

                const auto num_walks = static_cast<ssize_t>(walks.walk_set.num_walks());
                const auto walk_len = static_cast<ssize_t>(max_walk_len);

                auto rn = walks.walk_set.release_nodes();
                py::array_t<int> nodes_array(
                    py::array::ShapeContainer{num_walks, walk_len},
                    py::array::StridesContainer{static_cast<ssize_t>(sizeof(int) * max_walk_len), static_cast<ssize_t>(sizeof(int))},
                    static_cast<int*>(rn.ptr),
                    make_capsule(rn)
                );

                auto rt = walks.walk_set.release_timestamps();
                py::array_t<int64_t> timestamps_array(
                    py::array::ShapeContainer{num_walks, walk_len},
                    py::array::StridesContainer{static_cast<ssize_t>(sizeof(int64_t) * max_walk_len), static_cast<ssize_t>(sizeof(int64_t))},
                    static_cast<int64_t*>(rt.ptr),
                    make_capsule(rt)
                );

                auto rl = walks.walk_set.release_walk_lens();
                py::array_t<size_t> lens_array(
                    py::array::ShapeContainer{num_walks},
                    py::array::StridesContainer{static_cast<ssize_t>(sizeof(size_t))},
                    static_cast<size_t*>(rl.ptr),
                    make_capsule(rl)
                );

                py::object edge_features_array = py::none();
                if (walks.feature_dim > 0 && walks.walk_edge_features.size() > 0) {
                    const ssize_t edges_per_walk = static_cast<ssize_t>(std::max(0, max_walk_len - 1));
                    const auto feature_dim = static_cast<ssize_t>(walks.feature_dim);

                    auto re = walks.release_walk_edge_features();
                    edge_features_array = py::array_t<float>(
                        py::array::ShapeContainer{num_walks, edges_per_walk, feature_dim},
                        py::array::StridesContainer{
                            static_cast<ssize_t>(sizeof(float) * edges_per_walk * feature_dim),
                            static_cast<ssize_t>(sizeof(float) * feature_dim),
                            static_cast<ssize_t>(sizeof(float))},
                        static_cast<float*>(re.ptr),
                        make_capsule(re)
                    );
                }

                return std::make_tuple(nodes_array, timestamps_array, lens_array, edge_features_array);
            },
            R"(
            Generate temporal random walks with timestamps starting from all nodes.

            Args:
                max_walk_len (int): Maximum length of each random walk.
                walk_bias (str): Type of bias for selecting next node.
                    Choices:
                        - "Uniform": Equal probability
                        - "Linear": Linear time decay
                        - "ExponentialIndex": Exponential decay with indices
                        - "ExponentialWeight": Exponential decay with weights
                        - "TemporalNode2Vec": Temporal-node2vec transition bias
                num_walks_per_node (int): Number of walks per starting node.
                initial_edge_bias (str, optional): Bias type for first edge selection.
                    Uses walk_bias if not specified.
                walk_direction (str, optional): Direction of temporal random walks.
                    Either "Forward_In_Time" (default) or "Backward_In_Time".
                kernel_launch_type (str, optional): "NODE_GROUPED" (default),
                    "NODE_GROUPED_GLOBAL_ONLY" (ablation: coop without smem preload),
                    or "FULL_WALK" (one thread per walk, baseline).

            Returns:
                Tuple[np.ndarray, np.ndarray, np.ndarray, Optional[np.ndarray]]:
                    - 2D array of node ids (shape: [num_walks, max_walk_len])
                    - 2D array of timestamps (shape: [num_walks, max_walk_len])
                    - 1D array of actual walk lengths (shape: [num_walks])
                    - 3D array of edge features (shape: [num_walks, max_walk_len - 1, feature_dim]),
                      or None if feature_dim is 0
            )",
            py::arg("max_walk_len"),
            py::arg("walk_bias"),
            py::arg("num_walks_per_node"),
            py::arg("initial_edge_bias") = py::none(),
            py::arg("walk_direction") = "Forward_In_Time",
            py::arg("kernel_launch_type") = "NODE_GROUPED")

        .def("get_random_walks_and_times_for_last_batch", [](Tempest& tw,
                                               const int max_walk_len,
                                               const std::string& walk_bias,
                                               const int num_walks_per_node,
                                               const std::optional<std::string>& initial_edge_bias = std::nullopt,
                                               const std::string& walk_direction = "Forward_In_Time",
                                               const std::string& kernel_launch_type = "NODE_GROUPED")
            {
                const RandomPickerType walk_bias_enum = picker_type_from_string(walk_bias);
                std::optional<RandomPickerType> edge_bias_enum_opt;
                const RandomPickerType* initial_edge_bias_enum_ptr = get_picker_ptr_from_optional_string(
                    initial_edge_bias, edge_bias_enum_opt);
                const WalkDirection walk_direction_enum = walk_direction_from_string(walk_direction);
                const KernelLaunchType kernel_launch_type_enum =
                    kernel_launch_type_from_string(kernel_launch_type);

                auto walks = tw.get_random_walks_and_times_for_last_batch(
                    max_walk_len,
                    &walk_bias_enum,
                    num_walks_per_node,
                    initial_edge_bias_enum_ptr,
                    walk_direction_enum,
                    kernel_launch_type_enum);

                const auto num_walks = static_cast<ssize_t>(walks.walk_set.num_walks());
                const auto walk_len = static_cast<ssize_t>(max_walk_len);

                auto rn = walks.walk_set.release_nodes();
                py::array_t<int> nodes_array(
                    py::array::ShapeContainer{num_walks, walk_len},
                    py::array::StridesContainer{static_cast<ssize_t>(sizeof(int) * max_walk_len), static_cast<ssize_t>(sizeof(int))},
                    static_cast<int*>(rn.ptr),
                    make_capsule(rn)
